const assert = require('node:assert/strict');
const { compute } = require('./logic');
const s = {config:{panelCount:24,panelW:580,hsp:5,performance:80,chargeEfficiency:90,inverterEfficiency:92,dod:90,margin:10,batteryKwh:16,batteryUnits:1,inverterKW:16,batteryVoltage:51.2,batteryMaxCurrent:200,exchangeRate:27.02,tariff:0},strings:{series:8,stringsCount:3,mpptCount:3,voc:0,maxPVVoltage:0,maxMpptW:0,coldMultiplier:1.1},loads:[{name:'Aire inverter',quantity:2,averageW:650,peakW:1200,dayHours:0,nightHours:9,backed:true},{name:'Refrigeradora ENEE',quantity:1,averageW:120,peakW:350,dayHours:12,nightHours:12,backed:false}]};
let r=compute(s);
assert(Math.abs(r.demand-11.7)<1e-8);
assert(Math.abs(r.solarPotentialKwh-55.68)<1e-8);
assert(Math.abs(r.batteryUsableAC-13.248)<1e-8);
assert(Math.abs(r.runtimeHours-(13.248/1.3))<1e-8);
assert(Math.abs(r.batteryDischargeKW-(51.2*200*.92/1000))<1e-8);
assert.equal(r.grid,2.88);
assert.equal(r.solarOK,true);assert.equal(r.batteryOK,true);assert.equal(r.inverterOK,true);
assert.equal(r.stringPanels,24);assert.equal(r.stringsVerified,false);
let shortBattery=structuredClone(s);shortBattery.config.batteryKwh=5;
assert.equal(compute(shortBattery).batteryOK,false);
let weakInv=structuredClone(s);weakInv.config.inverterKW=2;
assert.equal(compute(weakInv).inverterOK,false);
let unsafeCurrent=structuredClone(s);unsafeCurrent.config.batteryMaxCurrent=15;
assert.equal(compute(unsafeCurrent).batteryPowerOK,false);
let badStrings=structuredClone(s);badStrings.strings={series:12,stringsCount:2,mpptCount:3,voc:52,maxPVVoltage:550,maxMpptW:6600,coldMultiplier:1.1};
assert(compute(badStrings).stringsWarnings.some(w=>w.includes('Voc')));
let empty=structuredClone(s);empty.loads=[];
assert.equal(compute(empty).recommendedPanels,0);
let day=structuredClone(s);day.loads=[{name:'Día',quantity:1,averageW:1000,peakW:1200,dayHours:5,nightHours:0,backed:true}];
assert.equal(compute(day).batteryRecommendedKwh,0);
